# BATCH CSV PREDICTION
print("\nBATCH PREDICTION")
print("Upload a CSV using the Colab Files panel, then set its path below.")

batch_path_widget = widgets.Text(
    value="/content/ai4i2020.csv",
    description="CSV path:",
    layout=widgets.Layout(width="600px")
)

batch_button = widgets.Button(
    description="Run Batch Predictions",
    button_style="success"
)

batch_output = widgets.Output()

def run_batch(_):
    with batch_output:
        clear_output(wait=True)

        path = batch_path_widget.value.strip()

        if not os.path.isfile(path):
            print("File not found:", path)
            return

        try:
            batch = pd.read_csv(path)
            batch.columns = batch.columns.str.strip()

            missing = [
                col for col in FEATURES if col not in batch.columns
            ]

            if missing:
                print("Missing required columns:", missing)
                return

            batch["Type"] = (
                batch["Type"].astype(str).str.upper().str.strip()
            )

            for col in FEATURES[1:]:
                batch[col] = pd.to_numeric(
                    batch[col], errors="coerce"
                )

            valid_mask = batch[FEATURES].notna().all(axis=1)
            valid_batch = batch.loc[valid_mask].copy()

            if valid_batch.empty:
                print("No valid records found.")
                return

            positive_index = list(best_model.classes_).index(1)
            probabilities = best_model.predict_proba(
                valid_batch[FEATURES]
            )[:, positive_index]

            batch_results = valid_batch.copy()
            batch_results["Failure Probability"] = probabilities
            batch_results["Prediction"] = np.where(
                probabilities >= 0.50,
                "Maintenance Alert",
                "No Alert"
            )

            output_path = (
                f"{OUTPUT_DIR}/batch_predictions.csv"
            )

            batch_results.to_csv(output_path, index=False)

            print("Valid records:", len(batch_results))
            print(
                "Machines flagged:",
                int((probabilities >= 0.50).sum())
            )
            print("Saved predictions to:", output_path)

            display(batch_results.head(20))

            from google.colab import files
            files.download(output_path)

        except Exception as exc:
            print("Batch prediction error:", exc)

batch_button.on_click(run_batch)

display(widgets.VBox([
    batch_path_widget,
    batch_button,
    batch_output
]))